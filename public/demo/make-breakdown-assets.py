#!/usr/bin/env python3
"""Assets for the depth breakdown film (depth-breakdown): the coffee photo at its display size
(1126 x 2000), the sill filled in behind the cup, the cup cut out, the photo split into the
layers the 3D view pulls apart (the street through the glass, the window and sill, the cup),
and the cup's outline as an SVG path for the lines that draw on.
Usage: make-breakdown-assets.py (after make-coffee-depth.py and make-coffee-mask.py)"""
import cv2
import numpy as np
from PIL import Image

DIR = __file__.rsplit("/", 1)[0]
ROOT = DIR.rsplit("/public/", 1)[0]
w, h = 1126, 2000
photo = np.asarray(Image.open(f"{DIR}/coffee.jpg").convert("RGB").resize((w, h), Image.LANCZOS))
cup = np.asarray(Image.open(f"{DIR}/coffee-cup-mask.png").convert("L").resize((w, h), Image.BILINEAR))
depth = np.asarray(Image.open(f"{DIR}/coffee-depth.png").convert("L").resize((w, h), Image.BILINEAR)) / 255

# the sill behind the cup, filled in
hole = cv2.dilate((cup > 8).astype(np.uint8), np.ones((9, 9), np.uint8))
# china the matte missed (the saucer's far rim) would streak across the sill: anything bright
# close to the cup is filled too
near_cup = cv2.dilate((cup > 8).astype(np.uint8), np.ones((41, 41), np.uint8)) > 0
bright = cv2.cvtColor(photo, cv2.COLOR_RGB2GRAY) > 140
hole = (hole > 0) | (near_cup & bright)
hole = cv2.dilate(hole.astype(np.uint8), np.ones((5, 5), np.uint8))


def fill_along(img, hole, u, max_t=900, mirror=False):
    """Fill a hole by carrying the picture straight through it along direction u: each hole
    pixel takes the first pixels outside the hole either way along u, weighted by nearness.
    The window rail and the sill's grain run along the window, so they continue straight
    behind the cup (a blind fill bent the rail into a curve: Scott, "fix this warp")."""
    h, w = hole.shape
    ys, xs = np.nonzero(hole)
    out = img.astype(np.float32).copy()
    found = {}
    for sgn in (1, -1):
        col = np.zeros((len(ys), 3), np.float32)
        dist = np.full(len(ys), np.inf, np.float32)
        todo = np.ones(len(ys), bool)
        for t in range(1, max_t):
            x = np.rint(xs + sgn * u[0] * t).astype(int)
            y = np.rint(ys + sgn * u[1] * t).astype(int)
            inside = (x >= 0) & (x < w) & (y >= 0) & (y < h)
            ok = todo & inside
            ok[ok] = hole[y[ok], x[ok]] == 0
            col[ok] = img[y[ok], x[ok]]
            if mirror:
                # mirrored about the hole's edge: the texture beyond carries in, no streaks
                xm = np.rint(xs + sgn * u[0] * 2 * t).astype(int)
                ym = np.rint(ys + sgn * u[1] * 2 * t).astype(int)
                okm = ok & (xm >= 0) & (xm < w) & (ym >= 0) & (ym < h)
                okm[okm] = hole[ym[okm], xm[okm]] == 0
                col[okm] = img[ym[okm], xm[okm]]
            dist[ok] = t
            todo &= ~ok
            todo &= inside  # ran off the photo: nothing that way
            if not todo.any():
                break
        found[sgn] = (col, dist)
    (c1, d1), (c2, d2) = found[1], found[-1]
    w1 = np.where(np.isfinite(d1), 1 / d1, 0)[:, None]
    w2 = np.where(np.isfinite(d2), 1 / d2, 0)[:, None]
    out[ys, xs] = (c1 * w1 + c2 * w2) / np.maximum(w1 + w2, 1e-6)
    return out.astype(np.uint8)


u = np.array([906.0, 510.0])
u /= np.linalg.norm(u)  # along the window's bottom edge
bg = fill_along(photo, hole, u)
# soften the fill's streaks a touch, inside the hole only
soft = cv2.GaussianBlur(bg, (0, 0), 1.2)
bg = np.where(hole[..., None] > 0, soft, bg)
Image.fromarray(bg).save(f"{DIR}/bd-bg.jpg", quality=92)
Image.fromarray(np.dstack([photo, cup])).save(f"{DIR}/bd-cup.png")

# the layers: the street through the glass (far), the window frame and sill, the cup
glass = (depth < 0.2).astype(np.uint8) * 255
glass = cv2.GaussianBlur(glass, (0, 0), 1.0)
Image.fromarray(np.dstack([bg, glass])).save(f"{DIR}/bd-far.png")
Image.fromarray(np.dstack([bg, 255 - glass])).save(f"{DIR}/bd-mid.png")

# the depth map in colour at the same size
colour = np.asarray(Image.open(f"{DIR}/coffee-depth-colour.png").convert("RGB").resize((w, h), Image.BILINEAR))
Image.fromarray(colour).save(f"{DIR}/bd-depth.jpg", quality=92)

# the cup's outline, for the lines that draw on
cs, _ = cv2.findContours((cup > 128).astype(np.uint8), cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
c = max(cs, key=cv2.contourArea)
c = cv2.approxPolyDP(c, 1.2, True)[:, 0, :]
path = "M" + " L".join(f"{x},{y}" for x, y in c) + " Z"
with open(f"{ROOT}/src/hotel-film/stings/depth-paths.ts", "w") as f:
    f.write("// Generated by public/demo/make-breakdown-assets.py: do not edit by hand.\n")
    f.write("// The coffee photo at 1126 x 2000: the cup's outline, traced from its matte.\n")
    f.write(f'export const CUP_OUTLINE = "{path}";\n')
print("bd-bg.jpg, bd-cup.png, bd-far.png, bd-mid.png, bd-depth.jpg, depth-paths.ts;", len(c), "points")

# the mountain, at its display size (1333 x 2000): its depth from MiDaS, the near hillside
# cut out (make-mountain-mask.py), the land behind it filled in for the lift, and its layers
mw, mh = 1333, 2000
mphoto = np.asarray(Image.open(f"{DIR}/mountain.jpg").convert("RGB").resize((mw, mh), Image.LANCZOS))
near = np.asarray(Image.open(f"{DIR}/mountain-near-mask.png").convert("L").resize((mw, mh), Image.BILINEAR))
mdepth = np.asarray(Image.open(f"{DIR}/mountain-depth.png").convert("L").resize((mw, mh), Image.BILINEAR)) / 255
mcol = np.asarray(Image.open(f"{DIR}/mountain-depth-colour.png").convert("RGB").resize((mw, mh), Image.BILINEAR))
Image.fromarray(mcol).save(f"{DIR}/bm-depth.jpg", quality=92)
Image.fromarray(np.dstack([mphoto, near])).save(f"{DIR}/bm-near-v2.png")
q = 2
mhole = cv2.dilate((near > 8).astype(np.uint8), np.ones((5, 5), np.uint8))
small = cv2.resize(mphoto, (mw // q, mh // q), interpolation=cv2.INTER_AREA)
filled = cv2.inpaint(small, cv2.resize(mhole, (mw // q, mh // q), interpolation=cv2.INTER_NEAREST), 8,
                     cv2.INPAINT_TELEA)
filled = cv2.resize(filled, (mw, mh), interpolation=cv2.INTER_CUBIC)
mbg = np.where(mhole[..., None] > 0, filled, mphoto)
Image.fromarray(mbg).save(f"{DIR}/bm-bg.jpg", quality=92)
# the far layer (sky and peaks) and the middle one (the lake and the valley), each with a hole
# where the hillside was
far = ((mdepth < 0.22) & (near < 128)).astype(np.uint8) * 255
far = cv2.GaussianBlur(far, (0, 0), 1.5)
rest = np.clip(255 - far.astype(np.int16) - near.astype(np.int16), 0, 255).astype(np.uint8)
# the far layer is solid (no holes to show as it swings): the scene with the land behind the
# hillside filled in and darkened, so what shows of it reads as shadow, not smear
shade = cv2.GaussianBlur(mhole.astype(np.float32), (0, 0), 12)[..., None]
farimg = (mbg.astype(np.float32) * (1 - 0.65 * shade)).astype(np.uint8)
# the middle layer is filled where the hillside was (the land behind it, darkened like the far
# layer), so it has no hillside- or walker-shaped hole in the lake to show as the layers part
# carried across sideways (the lake and the meadow run left to right), not darkened: as the
# hillside slides it uncovers more lake, not a dark wedge (Scott: "check the hole")
mid_rgb = fill_along(mphoto, mhole, np.array([1.0, 0.0]), max_t=1400, mirror=True)
# rows that are hillside edge to edge have nothing beside them: they keep the hillside itself,
# so where an edge of this layer shows past the hillside layer it reads as more meadow
blank = (mhole > 0) & (mid_rgb.sum(-1) == 0)
mid_rgb[blank] = mphoto[blank]
mid_rgb = np.where((mhole > 0)[..., None] & ~blank[..., None], cv2.GaussianBlur(mid_rgb, (0, 0), 1.5), mid_rgb)
# the mirror brings in water from further across the lake, lighter than the water by the cliff,
# so the fill showed as a pale box behind the rock as it moved: each row's tone is set to the
# water just past the hillside's edge, keeping the fill's own ripples
filled = (mhole > 0) & ~blank
ref = np.zeros((mh, 3), np.float32)
ok = np.zeros(mh, bool)
for y in range(mh):
    xs = np.nonzero(filled[y])[0]
    if len(xs) and xs.max() + 44 < mw:
        ref[y], ok[y] = mphoto[y, xs.max() + 4:xs.max() + 44].reshape(-1, 3).mean(0), True
ys = np.arange(mh)
ref = np.stack([np.interp(ys, ys[ok], ref[ok, c]) for c in range(3)], 1)
ref = cv2.GaussianBlur(ref[:, None, :], (0, 0), sigmaX=0.1, sigmaY=8)[:, 0, :]
f = mid_rgb.astype(np.float32)
lf = cv2.GaussianBlur(f, (0, 0), 30)
tuned = np.clip(f - lf + ref[:, None, :], 0, 255)
# eased in from the hole's edge so the join stays invisible
wgt = cv2.GaussianBlur(filled.astype(np.float32), (0, 0), 6)[..., None] * filled[..., None]
mid_rgb = (f * (1 - wgt) + tuned * wgt).astype(np.uint8)
Image.fromarray(np.dstack([mid_rgb, 255 - far])).save(f"{DIR}/bm-mid-v6.png")
# the far layer behind the hillside takes the same filled lake (its darkened fill showed as a
# dark box against the middle layer's water as the layers parted), darkened only where it is
# not lake and meadow, the rows the middle layer could not fill
farimg = np.where((mhole > 0)[..., None] & ~blank[..., None], mid_rgb, farimg)
Image.fromarray(np.dstack([farimg, np.full((mh, mw), 255, np.uint8)])).save(f"{DIR}/bm-far-v3.png")
print("bm-depth.jpg, bm-near-v2.png, bm-bg.jpg, bm-far-v3.png, bm-mid-v6.png")
# the hillside's outline, for its lines to draw on
cs, _ = cv2.findContours((near > 128).astype(np.uint8), cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
c = max(cs, key=cv2.contourArea)
c = cv2.approxPolyDP(c, 2.0, True)[:, 0, :]
# only the edge against the land behind, not the photo's own border
pts = [(x, y) for x, y in c if 2 < x < mw - 3 and y < mh - 3]
hill = "M" + " L".join(f"{x},{y}" for x, y in pts)
with open(f"{ROOT}/src/hotel-film/stings/depth-paths.ts", "a") as f:
    f.write("// The mountain photo at 1333 x 2000: the near hillside's edge, traced from its matte.\n")
    f.write(f'export const HILL_OUTLINE = "{hill}";\n')
print("HILL_OUTLINE:", len(pts), "points")
